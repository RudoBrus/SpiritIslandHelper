export function getMatchupTier(
  spiritOrAspectId: string,
  adversaryId: string,
): MatchupTier | null {
  const adversaryIndex = adversaryOrder.indexOf(adversaryId)

  if (adversaryIndex === -1) {
    return null
  }

  return matchupRatings[spiritOrAspectId]?.[adversaryIndex] ?? null
}
